const LanguageContext = createContext<LanguageContextType | undefined>(undefined);

const LANGUAGE_STORAGE_KEY = 'catchy_language';

/**
 * No explicit preference saved yet: the storefront's established default is
 * Arabic, but the admin dashboard — a different audience (staff, not
 * shoppers) — defaults to English instead. Both are still the *same* shared
 * preference once anyone (customer or staff) actually picks a language on
 * this browser; this only decides the very first, nothing-stored case. See
 * LanguageContext.test.ts.
 */
export function defaultLanguageForPath(pathname: string): Language {
  // Exact '/admin' or a '/admin/...' sub-route only — not a false-positive
  // prefix match against something like '/administration-policy'.
  return pathname === '/admin' || pathname.startsWith('/admin/') ? 'en' : 'ar';
}

function readStoredLanguage(): Language {
  let fallback: Language = 'ar';
  try {
    fallback = defaultLanguageForPath(window.location.pathname);
  } catch {
    // window/location unavailable (non-browser environment) — keep the 'ar' fallback.
  }
  try {
    const stored = localStorage.getItem(LANGUAGE_STORAGE_KEY);
    return stored === 'en' || stored === 'ar' ? stored : fallback;
  } catch {
    return fallback;
  }
}

export const LanguageProvider: React.FC<{ children: React.ReactNode }> = ({ children }) => {
  const [language, setLanguageState] = useState<Language>(readStoredLanguage);

  const setLanguage = (lang: Language) => {
    setLanguageState(lang);
    try {
      localStorage.setItem(LANGUAGE_STORAGE_KEY, lang);
    } catch {
      // Storage unavailable (private browsing, etc.) — the in-memory selection still applies this session.
    }
  };

  const t = (key: string) => {
    return translations[language][key] || key;
  };

  const isRTL = language === 'ar';

  useEffect(() => {
    document.documentElement.dir = isRTL ? 'rtl' : 'ltr';
    document.documentElement.lang = language;
  }, [language, isRTL]);

  return (
    <LanguageContext.Provider value={{ language, setLanguage, t, isRTL }}>
      <div dir={isRTL ? 'rtl' : 'ltr'} className={isRTL ? 'font-arabic' : ''}>
        {children}
      </div>
    </LanguageContext.Provider>
  );
};

export const useLanguage = () => {
  const context = useContext(LanguageContext);
  if (!context) throw new Error('useLanguage must be used within LanguageProvider');
  return context;
};
